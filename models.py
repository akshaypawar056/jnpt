from datetime import datetime, date
from database import db

class User(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(80), unique=True, nullable=False)
    password_hash = db.Column(db.String(255), nullable=False)
    role = db.Column(db.String(20), nullable=False, default="employee")
    employee_id = db.Column(db.Integer, db.ForeignKey("employee.id"))
    active = db.Column(db.Boolean, nullable=False, default=True)

class Employee(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    code = db.Column(db.String(40), unique=True, nullable=False)
    name = db.Column(db.String(120), nullable=False)
    department = db.Column(db.String(100))
    designation = db.Column(db.String(100))
    email = db.Column(db.String(150))
    phone = db.Column(db.String(40))
    manager = db.Column(db.String(120))
    active = db.Column(db.Boolean, nullable=False, default=True)

class Project(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    code = db.Column(db.String(50), unique=True, nullable=False)
    name = db.Column(db.String(160), nullable=False)
    client = db.Column(db.String(160))
    manager = db.Column(db.String(120))
    start_date = db.Column(db.Date)
    end_date = db.Column(db.Date)
    budget = db.Column(db.Numeric(14, 2), default=0)
    status = db.Column(db.String(30), default="Active")

class Travel(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    employee_id = db.Column(db.Integer, db.ForeignKey("employee.id"), nullable=False)
    project_id = db.Column(db.Integer, db.ForeignKey("project.id"), nullable=False)
    travel_date = db.Column(db.Date, nullable=False)
    return_date = db.Column(db.Date)
    origin = db.Column(db.String(120))
    destination = db.Column(db.String(120))
    purpose = db.Column(db.String(255))
    mode = db.Column(db.String(60))
    hotel = db.Column(db.String(160))
    advance = db.Column(db.Numeric(14, 2), default=0)
    status = db.Column(db.String(30), default="Pending")
    manager_note = db.Column(db.String(255))
    employee = db.relationship("Employee")
    project = db.relationship("Project")

class Expense(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    claim_no = db.Column(db.String(40), unique=True, nullable=False)
    employee_id = db.Column(db.Integer, db.ForeignKey("employee.id"), nullable=False)
    project_id = db.Column(db.Integer, db.ForeignKey("project.id"), nullable=False)
    travel_id = db.Column(db.Integer, db.ForeignKey("travel.id"))
    expense_date = db.Column(db.Date, nullable=False)
    category = db.Column(db.String(80), nullable=False)
    description = db.Column(db.String(255))
    amount = db.Column(db.Numeric(14, 2), default=0)
    gst = db.Column(db.Numeric(14, 2), default=0)
    payment_method = db.Column(db.String(50))
    receipt = db.Column(db.String(255))
    status = db.Column(db.String(30), default="Pending Manager")
    manager_note = db.Column(db.String(255))
    finance_note = db.Column(db.String(255))
    employee = db.relationship("Employee")
    project = db.relationship("Project")
    travel = db.relationship("Travel")

class Advance(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    advance_no = db.Column(db.String(40), unique=True, nullable=False)
    employee_id = db.Column(db.Integer, db.ForeignKey("employee.id"), nullable=False)
    project_id = db.Column(db.Integer, db.ForeignKey("project.id"), nullable=False)
    travel_id = db.Column(db.Integer, db.ForeignKey("travel.id"))
    request_date = db.Column(db.Date, default=date.today)
    amount = db.Column(db.Numeric(14, 2), default=0)
    purpose = db.Column(db.String(255))
    status = db.Column(db.String(30), default="Pending Manager")
    paid_date = db.Column(db.Date)
    employee = db.relationship("Employee")
    project = db.relationship("Project")
    travel = db.relationship("Travel")

class AuditLog(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    username = db.Column(db.String(80))
    action = db.Column(db.String(120))
    entity = db.Column(db.String(80))
    entity_id = db.Column(db.Integer)
    details = db.Column(db.String(500))
